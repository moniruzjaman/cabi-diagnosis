#!/usr/bin/env node
// ─── Post-build crossorigin removal + version stamping ──────────────────────
// This script runs AFTER `vite build` as a final safety net.
//
// Part 1 — strip crossorigin from dist/index.html (historical Layer 4 fix):
//   removes crossorigin from <script> and <link rel="stylesheet"> tags so
//   Vercel's CDN never serves a CORS-broken shell. crossorigin is KEPT on
//   <link rel="preconnect"> for Google Fonts (it's required).
//
// Part 2 — stamp build metadata into the built artifacts (new):
//   - dist/index.html gets <meta name="app-version"> / "build-commit" /
//     "build-time" tags so the deployed shell self-describes its build
//     (visible to curl/uptime checks without booting the JS bundle).
//   - dist/manifest.json gets "version" + "version_name" from package.json
//     so the PWA manifest carries the real app version.
//   Values come from src/buildMeta.js, generated by
//   scripts/generate-build-meta.mjs in the same build run.

import { readFileSync, writeFileSync, existsSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const distDir = resolve(__dirname, "..", "dist");
const htmlPath = resolve(distDir, "index.html");
const manifestPath = resolve(distDir, "manifest.json");

function stripCrossorigin(html) {
  // Remove crossorigin from <script> tags
  html = html.replace(
    /(<script\b[^>]*?)\s+crossorigin(?:\s*=\s*(?:"[^"]*"|'[^']*'))?([^>]*?>)/gi,
    "$1$2",
  );
  // Remove crossorigin from <link rel="stylesheet"> tags ONLY
  html = html.replace(
    /(<link\b[^>]*?rel\s*=\s*(?:"stylesheet"|'stylesheet')[^>]*?)\s+crossorigin(?:\s*=\s*(?:"[^"]*"|'[^']*'))?([^>]*?(?:\/>|>))/gi,
    "$1$2",
  );
  return html;
}

// ─── Part 1: crossorigin strip ───────────────────────────────────────────────
try {
  let html = readFileSync(htmlPath, "utf-8");
  const original = html;
  html = stripCrossorigin(html);

  if (html !== original) {
    writeFileSync(htmlPath, html, "utf-8");
    console.log("[strip-crossorigin] Stripped crossorigin from dist/index.html");
  } else {
    console.log("[strip-crossorigin] dist/index.html is clean (no crossorigin on script/stylesheet)");
  }
} catch (e) {
  console.warn("[strip-crossorigin] Warning:", e.message);
  process.exit(0); // Don't fail the build
}

// ─── Part 2: version stamping ────────────────────────────────────────────────
async function stampBuildMetadata() {
  const { APP_VERSION, BUILD_COMMIT, BUILD_TIME } = await import("../src/buildMeta.js");

  // 2a. dist/index.html — self-describing shell
  try {
    let html = readFileSync(htmlPath, "utf-8");
    const metaTags = `  <meta name="app-version" content="${APP_VERSION}" />\n  <meta name="build-commit" content="${BUILD_COMMIT}" />\n  <meta name="build-time" content="${BUILD_TIME}" />`;

    // Replace existing stamps if present (idempotent re-runs), else inject
    // right after <head> opening (keeps charset/viewport first per HTML5).
    if (/name="app-version"/.test(html)) {
      html = html.replace(
        /[ \t]*<meta name="app-version" content="[^"]*" \/>\n[ \t]*<meta name="build-commit" content="[^"]*" \/>\n[ \t]*<meta name="build-time" content="[^"]*" \/>/,
        metaTags,
      );
    } else {
      html = html.replace(/<head>/, `<head>\n${metaTags}`);
    }
    writeFileSync(htmlPath, html, "utf-8");
    console.log(`[build-stamp] dist/index.html stamped: v${APP_VERSION} @ ${BUILD_COMMIT}`);
  } catch (e) {
    console.warn("[build-stamp] index.html stamp failed:", e.message);
  }

  // 2b. dist/manifest.json — real version in the PWA manifest
  try {
    if (existsSync(manifestPath)) {
      const manifest = JSON.parse(readFileSync(manifestPath, "utf-8"));
      manifest.version = APP_VERSION;
      manifest.version_name = `v${APP_VERSION}`;
      writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n", "utf-8");
      console.log(`[build-stamp] dist/manifest.json stamped: v${APP_VERSION}`);
    }
  } catch (e) {
    console.warn("[build-stamp] manifest.json stamp failed:", e.message);
  }
}

stampBuildMetadata();

