/**
 * validate-image-names.mjs
 *
 * Validates CABI image file names, public/database.json, and the legacy alias map
 * against IMAGE_NAMING_CONVENTION.md.
 *
 * Exit code: 0 = all valid, 1 = one or more violations.
 *
 * Usage:
 *   node scripts/validate-image-names.mjs
 *   node scripts/validate-image-names.mjs --public-dir public --images-dir public/images
 */

import { readFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join } from "node:path";

// ????????? Configuration ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
const PUBLIC_DIR = process.argv.includes("--public-dir")
  ? process.argv[process.argv.indexOf("--public-dir") + 1]
  : "public";
const IMAGES_DIR = process.argv.includes("--images-dir")
  ? process.argv[process.argv.indexOf("--images-dir") + 1]
  : join(PUBLIC_DIR, "images");

const DB_PATH = join(PUBLIC_DIR, "database.json");
const LEGACY_MAP_PATH = join(PUBLIC_DIR, "IMAGE_NAME_LEGACY_MAP.json");

// Canonical categoryEn slugs from IMAGE_NAMING_CONVENTION.md.
const CANONICAL_CATEGORY_EN = new Set([
  "leaf_spot",
  "drying_necrosis_blight",
  "mosaic",
  "witches_broom",
  "galls",
  "wilt",
  "little_leaf",
  "canker",
  "cover_front_matter",
]);

// Validation regex (mirrors the doc).
// ^\d{3}_<categoryEn>_<categoryBn>_<signSymptomBn>_<seq>.<ext>
const NAME_RE =
  /^(\d{3})_([a-z0-9]+(?:_[a-z0-9]+)*)_(.+)_(\d+)\.(jpe?g|png)$/i;

// ????????? Helpers ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
const errors = [];
const warnings = [];

function fail(msg) {
  errors.push(msg);
  console.error(`??? ${msg}`);
}

function warn(msg) {
  warnings.push(msg);
  console.warn(`??? ${msg}`);
}

/**
 * Check that a string is NFC-normalized. Returns the normalized string and a
 * flag if normalization changed anything.
 */
/**
 * Read a text file as UTF-8, stripping a leading BOM (U+FEFF) if present.
 * Node.js does not support the "utf-8-sig" codec, so we handle BOM manually.
 */
function readText(path) {
  let text = readFileSync(path, "utf8");
  if (text.charCodeAt(0) === 0xfeff) {
    text = text.slice(1);
  }
  return text;
}

function assertNFC(label, value) {
  const normalized = value.normalize("NFC");
  const changed = normalized !== value;
  if (changed) {
    fail(`${label}: not NFC-normalized.`);
    fail(`    found:      ${JSON.stringify(value)}`);
    fail(`    expected:   ${JSON.stringify(normalized)}`);
  }
  return { normalized, changed };
}

/**
 * Parse a file name into { page, categoryEn, middle, seq, ext }.
 * Returns null if the name does not match the convention.
 */
function parseName(fileName) {
  const m = fileName.match(NAME_RE);
  if (!m) return null;
  return {
    page: m[1],
    categoryEn: m[2],
    middle: m[3],
    seq: Number(m[4]),
    ext: m[5].toLowerCase(),
  };
}

// ????????? Step 1: validate files on disk ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
function validateDisk() {
  console.log(`\n== Validating files in ${IMAGES_DIR} ==`);
  if (!existsSync(IMAGES_DIR)) {
    fail(`images directory not found: ${IMAGES_DIR}`);
    return new Map();
  }

  const files = readdirSync(IMAGES_DIR).filter((f) => {
    const st = statSync(join(IMAGES_DIR, f));
    return st.isFile();
  });

  const onDisk = new Map();
  for (const f of files) {
    onDisk.set(f, true);
    const parsed = parseName(f);
    if (!parsed) {
      fail(`file name does not match convention: ${f}`);
      continue;
    }

    // categoryEn must be canonical.
    if (!CANONICAL_CATEGORY_EN.has(parsed.categoryEn)) {
      fail(`${f}: categoryEn "${parsed.categoryEn}" is not in the canonical glossary.`);
    }

    // seq must be a non-negative integer.
    if (!Number.isInteger(parsed.seq) || parsed.seq < 0) {
      fail(`${f}: seq must be a non-negative integer, got ${parsed.seq}.`);
    }

    // ext must be lowercase.
    if (parsed.ext !== f.split(".").pop().toLowerCase()) {
      fail(`${f}: extension should be lowercase.`);
    }

    // Check NFC on the Bengali segment (the `middle` field).
    assertNFC(`${f}: Bengali segment`, parsed.middle);
  }

  return onDisk;
}

// ????????? Step 2: validate database.json images[] ???????????????????????????????????????????????????????????????????????????????????????????????????
function validateDatabase(onDisk) {
  console.log(`\n== Validating ${DB_PATH} ==`);
  if (!existsSync(DB_PATH)) {
    fail(`database.json not found: ${DB_PATH}`);
    return;
  }

  let db;
  try {
    db = JSON.parse(readText(DB_PATH));
  } catch (e) {
    fail(`database.json is not valid JSON: ${e.message}`);
    return;
  }

  const keys = db.diagnostic_keys || [];
  let totalImages = 0;
  let missingOnDisk = 0;

  for (const page of keys) {
    const pageNo = String(page.page ?? "").padStart(3, "0");
    const images = page.images || [];
    totalImages += images.length;

    for (const img of images) {
      const parsed = parseName(img);
      if (!parsed) {
        fail(`database.json page ${pageNo}: invalid image name "${img}".`);
        continue;
      }

      if (parsed.page !== pageNo) {
        fail(
          `database.json page ${pageNo}: image "${img}" page token "${parsed.page}" does not match database page.`,
        );
      }

      if (!onDisk.has(img)) {
        missingOnDisk++;
        fail(`database.json page ${pageNo}: image "${img}" referenced but missing on disk.`);
      }

      assertNFC(`database.json page ${pageNo}: ${img}`, parsed.middle);
    }
  }

  console.log(`    database.json: ${keys.length} pages, ${totalImages} image references.`);
  if (missingOnDisk > 0) {
    fail(`${missingOnDisk} image(s) referenced in database.json are missing on disk.`);
  }
}

// ????????? Step 3: validate legacy alias map ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
function validateLegacyMap(onDisk) {
  console.log(`\n== Validating ${LEGACY_MAP_PATH} ==`);
  if (!existsSync(LEGACY_MAP_PATH)) {
    warn(`legacy map not found (optional): ${LEGACY_MAP_PATH}`);
    return;
  }

  let map;
  try {
    map = JSON.parse(readText(LEGACY_MAP_PATH));
  } catch (e) {
    fail(`IMAGE_NAME_LEGACY_MAP.json is not valid JSON: ${e.message}`);
    return;
  }

  const entries = Object.entries(map);
  let legacyKeyBad = 0;
  let valueMissing = 0;
  let valueInvalid = 0;

  for (const [legacyName, newName] of entries) {
    if (!/^img_page\d+_\d+\.(jpe?g|png)$/i.test(legacyName)) {
      legacyKeyBad++;
      fail(`legacy map: key "${legacyName}" does not look like a legacy img_pageXX_Y name.`);
    }

    const parsed = parseName(String(newName));
    if (!parsed) {
      valueInvalid++;
      fail(`legacy map: value for "${legacyName}" is not a valid new-style name: "${newName}".`);
    } else if (!onDisk.has(String(newName))) {
      valueMissing++;
      fail(`legacy map: value for "${legacyName}" ("${newName}") is missing on disk.`);
    }
  }

  console.log(`    legacy map: ${entries.length} entries.`);
  if (legacyKeyBad > 0) fail(`${legacyKeyBad} legacy key(s) malformed.`);
  if (valueInvalid > 0) fail(`${valueInvalid} legacy value(s) invalid.`);
  if (valueMissing > 0) fail(`${valueMissing} legacy value(s) missing on disk.`);
}

// ????????? Step 4: seq continuity per (page, categoryEn) ?????????????????????????????????????????????????????????????????????????????????
function checkSeqContinuity(onDisk) {
  console.log(`\n== Checking seq continuity ==`);
  const groups = new Map();
  for (const f of onDisk.keys()) {
    const parsed = parseName(f);
    if (!parsed) continue;
    const key = `${parsed.page}_${parsed.categoryEn}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(parsed.seq);
  }

  let seqIssues = 0;
  for (const [key, seqs] of groups) {
    const sorted = [...seqs].sort((a, b) => a - b);
    if (sorted[0] !== 0) {
      seqIssues++;
      fail(`seq continuity: ${key} starts at ${sorted[0]}, expected 0.`);
    }
    for (let i = 1; i < sorted.length; i++) {
      if (sorted[i] !== sorted[i - 1] + 1) {
        seqIssues++;
        fail(`seq continuity: ${key} has gap (???${sorted[i - 1]}, ${sorted[i]}???).`);
        break;
      }
    }
  }

  if (seqIssues === 0 && groups.size > 0) {
    console.log(`    seq continuity OK across ${groups.size} (page, category) groups.`);
  } else if (groups.size === 0) {
    console.log(`    no groups to check.`);
  } else {
    fail(`${seqIssues} group(s) have seq continuity issues.`);
  }
}


// ????????? Main ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
function main() {
  console.log("CABI image naming convention validator\n");
  const onDisk = validateDisk();
  validateDatabase(onDisk);
  validateLegacyMap(onDisk);
  checkSeqContinuity(onDisk);

  console.log(`\n== Summary ==`);
  console.log(`    errors:   ${errors.length}`);
  console.log(`    warnings: ${warnings.length}`);

  if (errors.length > 0) {
    console.error("\nValidation FAILED.");
    process.exit(1);
  }
  console.log("\nValidation PASSED.");
  process.exit(0);
}

main();

