/**
 * renormalize-image-names.mjs ??? dry-run by default; pass --write to apply.
 * Reconstructs correct CABI image names from IMAGE_NAMING_CONVENTION.md.
 * Mojibake affects only Bengali tokens; page/categoryEn/seq/ext are ASCII.
 * Updates public/images/, public/database.json images[], legacy map values.
 */

import { readFileSync, readdirSync, statSync, existsSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const WRITE = process.argv.includes("--write");
const PUBLIC_DIR = (() => { const i = process.argv.indexOf("--public-dir"); return i === -1 ? "public" : process.argv[i + 1]; })();
const IMAGES_DIR = (() => { const i = process.argv.indexOf("--images-dir"); return i === -1 ? join(PUBLIC_DIR, "images") : process.argv[i + 1]; })();
const DB_PATH = join(PUBLIC_DIR, "database.json");
const LEGACY_MAP_PATH = join(PUBLIC_DIR, "IMAGE_NAME_LEGACY_MAP.json");
const NAME_RE = /^(\d{3})_([a-z0-9]+(?:_[a-z0-9]+)*)_(.+)_(\d+)\.(jpe?g|png)$/i;

const GLOSSARY = {
  leaf_spot: { categoryBn: "??????????????????_?????????", signSymptomBn: "?????????????????????_???????????????_?????????" },
  drying_necrosis_blight: { categoryBn: "?????????????????????_?????????", signSymptomBn: "????????????_?????????????????????_??????????????????" },
  mosaic: { categoryBn: "??????????????????", signSymptomBn: "????????????_????????????_????????????_??????????????????" },
  witches_broom: { categoryBn: "?????????????????????_????????????????????????", signSymptomBn: "?????????_???????????????_???????????????" },
  galls: { categoryBn: "????????????_????????????", signSymptomBn: "???????????????_???????????????_????????????" },
  wilt: { categoryBn: "?????????_?????????????????????", signSymptomBn: "????????????_?????????????????????_????????????" },
  little_leaf: { categoryBn: "?????????_????????????", signSymptomBn: "????????????_???????????????????????????_????????????_?????????" },
  canker: { categoryBn: "????????????????????????_???????????????_?????????", signSymptomBn: "?????????????????????_????????????_?????????" },
  cover_front_matter: { categoryBn: "?????????????????????_??????????????????", signSymptomBn: "?????????????????????_?????????????????????" },
};

const changes = [];
const readText = (p) => { let t = readFileSync(p, "utf8"); if (t.charCodeAt(0) === 0xfeff) t = t.slice(1); return t; };
const parseName = (f) => { const m = f.match(NAME_RE); return m ? { page: m[1], categoryEn: m[2], seq: Number(m[4]), ext: m[5].toLowerCase() } : null; };
const canon = (p) => { const g = GLOSSARY[p.categoryEn]; return g ? `${p.page}_${p.categoryEn}_${g.categoryBn}_${g.signSymptomBn}_${p.seq}.${p.ext}` : null; };

const note = (kind, path, old, nu, reason) => {
  changes.push({ kind, path, old, nu, reason });
  console.log(`  [${kind}] ${path}\n    ${old}\n    ${WRITE ? "???" : "would ???"} ${nu}   (${reason})`);
};

// ---- Step 1: files on disk --------------------------------------------------
let onDisk = new Map();
console.log(`\n== Renormalizing ${IMAGES_DIR} ${WRITE ? "(WRITE)" : "(dry-run)"} ==`);
if (existsSync(IMAGES_DIR)) {
  const files = readdirSync(IMAGES_DIR).filter((f) => statSync(join(IMAGES_DIR, f)).isFile());
  const toRename = [];
  for (const f of files) {
    const p = parseName(f);
    if (!p) { note("skip", IMAGES_DIR, f, f, "does not match convention"); onDisk.set(f, true); continue; }
    const c = canon(p);
    if (!c) { note("skip", IMAGES_DIR, f, f, `categoryEn "${p.categoryEn}" not in glossary`); onDisk.set(f, true); continue; }
    if (f === c) { onDisk.set(c, true); continue; }
    if (onDisk.has(c)) { note("conflict", IMAGES_DIR, f, c, "target already exists"); onDisk.set(f, true); continue; }
    toRename.push({ old: f, new: c });
    onDisk.set(c, true);
  }
  toRename.sort((a, b) => a.old.localeCompare(b.new));
  for (const { old, new: nu } of toRename) {
    note("rename", IMAGES_DIR, old, nu, "Bengali ??? glossary-correct");
    if (WRITE) { try { renameSync(join(IMAGES_DIR, old), join(IMAGES_DIR, nu)); } catch (e) { console.error(`    FAILED ${old}: ${e.message}`); } }
  }
  console.log(`  ${toRename.length} file(s) ${WRITE ? "renamed" : "to be renamed"}.`);
} else { console.log(`  (not found)`); }

// ---- Step 2: database.json --------------------------------------------------
console.log(`\n== Renormalizing ${DB_PATH} ${WRITE ? "(WRITE)" : "(dry-run)"} ==`);
let dbPages = 0, dbImgs = 0;
if (existsSync(DB_PATH)) {
  let db;
  try { db = JSON.parse(readText(DB_PATH)); } catch (e) { console.error(`  FAILED parse: ${e.message}`); db = null; }
  if (db) {
    for (const page of db.diagnostic_keys || []) {
      const pageNo = String(page.page ?? "").padStart(3, "0");
      const imgs = page.images || [];
      let changed = false;
      const next = [];
      for (const img of imgs) {
        const p = parseName(img);
        if (!p) { next.push(img); continue; }
        const c = canon(p);
        if (!c || img === c) { next.push(img); continue; }
        next.push(c); changed = true; dbImgs++;
        note("db", `page ${pageNo}`, img, c, "database reference");
      }
      if (changed) { dbPages++; if (WRITE) page.images = next; }
    }
    if (WRITE && dbPages > 0) { try { writeFileSync(DB_PATH, JSON.stringify(db, null, 2) + "\n", "utf8"); console.log(`  wrote ${DB_PATH}`); } catch (e) { console.error(`  FAILED write: ${e.message}`); } }
    console.log(`  ${dbPages} page(s), ${dbImgs} image reference(s) ${WRITE ? "updated" : "to be updated"}.`);
  }
} else { console.log(`  (not found)`); }

// ---- Step 3: legacy map -----------------------------------------------------
console.log(`\n== Renormalizing ${LEGACY_MAP_PATH} ${WRITE ? "(WRITE)" : "(dry-run)"} ==`);
let leg = 0;
if (existsSync(LEGACY_MAP_PATH)) {
  let map;
  try { map = JSON.parse(readText(LEGACY_MAP_PATH)); } catch (e) { console.error(`  FAILED parse: ${e.message}`); map = null; }
  if (map) {
    const out = {};
    for (const [k, v] of Object.entries(map)) {
      const cur = String(v); const p = parseName(cur); let nv = cur;
      if (p) { const c = canon(p); if (c) { nv = c; if (cur !== c) { leg++; note("legacy", LEGACY_MAP_PATH, k + " ??? " + cur, k + " ??? " + c, "legacy value"); } } }
      out[k] = nv;
    }
    if (WRITE && leg > 0) { try { writeFileSync(LEGACY_MAP_PATH, JSON.stringify(out, null, 2) + "\n", "utf8"); console.log(`  wrote ${LEGACY_MAP_PATH}`); } catch (e) { console.error(`  FAILED write: ${e.message}`); } }
    console.log(`  ${leg} legacy value(s) ${WRITE ? "updated" : "to be updated"}.`);
  }
} else { console.log(`  (not found, optional)`); }

// ---- Summary -----------------------------------------------------------------
console.log(`\n== Summary ==`);
console.log(`  total changes detected: ${changes.length}`);
if (!WRITE) console.log(`  (dry-run: nothing written. Re-run with --write to apply.)`);
else console.log(`  applied. Now run: node scripts/validate-image-names.mjs`);

